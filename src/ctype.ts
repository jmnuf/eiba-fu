export type char = ui8 & {};
export const char = (s: string): char => s.charCodeAt(0) as char;


const space_chars = [
  0x20, // Space ' '
  0x0C, // Form feed '\f'
  0x0A, // Line feed '\n'
  0x0D, // Carriage return '\r'
  0x09, // Horizontal tab '\t'
  0x0B, // Vertical tab '\v'
] as const;

export function isspace(c: char) {
  return space_chars.includes(c as any);
}

const DIGIT_0_CHAR = 48;
const DIGIT_9_CHAR = 57;
const CAPITAL_A_CHAR = 65;
const CAPITAL_Z_CHAR = 90;
const LOWER_A_CHAR = 97;
const LOWER_Z_CHAR = 122;

export function isalpha(c: char) {
  if (CAPITAL_A_CHAR <= c && c <= CAPITAL_Z_CHAR) return true;
  if (LOWER_A_CHAR <= c && c <= LOWER_Z_CHAR) return true;
  return false;
}

export function isdigit(c: char) {
  return DIGIT_0_CHAR <= c && c <= DIGIT_9_CHAR;
}

export function isalnum(c: char) {
  if (c < DIGIT_0_CHAR) return false;
  if (c > LOWER_Z_CHAR) return false;
  return isdigit(c) || isalpha(c);
}

